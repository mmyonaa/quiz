/** 개념 노트·해설의 강조 표기 — 세 층을 편다. 나머지 문자는 그대로 이스케이프해
    포인터 *p, 시프트 <<, 논리 && 같은 본문 기호가 마크업으로 새지 않게 한다.

    층이 셋인 이유 — 굵게 하나가 용어·수치·대조 짝·경고를 다 칠하고 있었다.
    전부 같은 무게라 눈이 우선순위를 못 잡았고, 한 도입부에 굵게가 13개까지
    불어난 곳도 있었다. 강조가 강조를 죽인 것이다. 이제 셋으로 갈린다 —

      ==형광펜==  외울 한 줄·대조 짝·단골 함정. 주제당 한두 군데가 상한이고,
                  열거형은 설명구를 본문에 두고 낱말에만 칠한다(길게 칠하면 문단이 된다)
      **용어**    용어와 분류 이름
      `값`        그대로 외워야 하는 수치·명령·경로

    빌드 타임(개념 노트)과 브라우저(마이페이지)가 같은 규칙을 써야 하므로 여기 둔다 —
    두 곳에 각자 두면 한쪽만 고쳐져 같은 데이터가 화면마다 다르게 읽힌다.

    `백틱`은 이미 데이터에 쓰여 있었는데 어느 화면도 펴지 않아 본문에 백틱 문자가
    그대로 노출돼 있었다(개념 도입부 60군데, 해설 5군데 — 빌드물에서 확인).

    ==는 C 관계 연산자 ==와 글자가 겹친다. 여는 쪽 뒤와 닫는 쪽 앞의 공백을 금해
    갈랐다 — 코드의 ==는 관례대로 `i % 2 == 1`처럼 양옆에 공백을 두므로 여는 쪽에서
    걸러진다(해설 974개를 전수 검사해 잘못 잡히는 것이 없음을 확인했다). 공백 없는
    `a==b`를 한 문단에 둘 이상 쓰면 형광펜으로 잡힐 수 있으니 그때는 백틱으로 감싼다. */
const ESC: Record<string, string> = { "&": "&amp;", "<": "&lt;", ">": "&gt;" };

export const md = (s: string) =>
  s
    .replace(/[&<>]/g, (c) => ESC[c])
    .replace(/==(?=\S)([^=\n]+)(?<=\S)==/g, '<mark class="hl">$1</mark>')
    .replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>")
    // mono는 키보드로 그대로 치는 값에만 준다 — 한글이 섞인 수치("1년 이상")를 mono로
    // 세우면 낱말 사이가 벌어져 두 낱말처럼 읽힌다. 칩 자체는 둘 다 받는다.
    //
    // long은 줄바꿈을 허용하는 칩이다. 칩은 기본적으로 줄 끝에서 쪼개지지 않는데("5만 명"이
    // "5만"/"명"으로 갈리면 값 하나가 둘로 보인다), 그 규칙이 긴 값에는 해롭다 — Snort 룰
    // 한 줄(76자)이 390px 화면에서 판 밖으로 421px까지 밀려났다. 경계는 30자다:
    // 전체 1,222개 중 30자를 넘는 것이 6개뿐이라, 짧은 값의 nowrap은 그대로 두면서
    // 넘치는 것만 고른다.
    .replace(/`([^`\n]+)`/g, (_, v) =>
      `<code class="val${/^[\x20-\x7e]+$/.test(v) ? " mono" : ""}${v.length > 30 ? " long" : ""}">${v}</code>`,
    );
